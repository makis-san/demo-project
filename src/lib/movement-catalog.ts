import type { Equipment, MuscleGroup } from "@/lib/muscles";
import { P, type FigureDef } from "@/components/movement-figure/rig";

/**
 * The built-in movements. This is product data: it changes with releases, not per user, so it lives in code and
 * the seed (scripts/seed-movements.ts) writes it to the Movement table, upserting on `slug`. Adding a movement here
 * and restarting adds it for everyone. The `slug` is the movement's identity: rename `name` freely, never the slug.
 *
 * The muscles, equipment and body-weight flag are stored in the database, because queries read them. The steps, the
 * "watch for" line and the animation poses are presentation, so they stay here and the movement page reads them
 * by slug. A movement without `figure` shows the body map and the steps without the animated side view.
 */
export type CatalogMovement = {
  slug: string;
  name: string;
  equipment: Equipment;
  isBodyWeight: boolean;
  primaryMuscles: MuscleGroup[];
  secondaryMuscles: MuscleGroup[];
  /** Set up, the first half of the rep, the second half. The animation highlights them in time. */
  steps: [string, string, string];
  watch: string;
  figure?: FigureDef;
};

function m(
  slug: string,
  name: string,
  equipment: Equipment,
  primaryMuscles: MuscleGroup[],
  secondaryMuscles: MuscleGroup[],
  steps: [string, string, string],
  watch: string,
  options: { bodyWeight?: boolean; figure?: FigureDef } = {},
): CatalogMovement {
  return {
    slug,
    name,
    equipment,
    isBodyWeight: options.bodyWeight ?? false,
    primaryMuscles,
    secondaryMuscles,
    steps,
    watch,
    figure: options.figure,
  };
}

