/** The middle of an outline, so a muscle can swell around it. */
export function centreOf(outline: string): [number, number] {
  const n = outline.match(/-?\d*\.?\d+/g)!.map(Number);
  const xs: number[] = [];
  const ys: number[] = [];
  for (let i = 0; i + 1 < n.length; i += 2) {
    xs.push(n[i]);
    ys.push(n[i + 1]);
  }
  return [(Math.min(...xs) + Math.max(...xs)) / 2, (Math.min(...ys) + Math.max(...ys)) / 2];
}

